"""Abstract domain interface used by the generic forward/backward analysis."""

from __future__ import annotations

from collections.abc import Sequence
from typing import Protocol


class Domain[A](Protocol):
    def top(self) -> A: ...
    def bottom(self) -> A: ...
    def alpha(self, value: int | str) -> A: ...
    def is_bottom(self, a: A) -> bool: ...
    def leq(self, a: A, b: A) -> bool: ...
    def join(self, a: A, b: A) -> A: ...
    def meet(self, a: A, b: A) -> A: ...
    def forward(self, op: str, args: Sequence[A]) -> A:
        """Abstract result of op; raises UnsupportedOperator for unknown ops."""
        ...

    def backward(self, op: str, result: A, args: Sequence[A], i: int) -> A:
        """Necessary precondition for argument i given the result and all current arguments."""
        ...
